-- Exclusivamente para una base de datos local de simulacion. No introducir datos bancarios reales.
BEGIN;
CREATE SCHEMA IF NOT EXISTS pasarela;
CREATE TABLE IF NOT EXISTS pasarela.tarjetas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titular_dni varchar(8) NOT NULL REFERENCES public.usuarios(dni),
 numero_tarjeta varchar(19) NOT NULL UNIQUE CHECK (numero_tarjeta ~ '^DEMO-[0-9]{8}$'),
 nombre_titular varchar(150) NOT NULL,
 mes_vencimiento smallint NOT NULL CHECK (mes_vencimiento BETWEEN 1 AND 12),
 anio_vencimiento smallint NOT NULL CHECK (anio_vencimiento BETWEEN 2026 AND 2199),
 cvv_hash varchar(255) NOT NULL,
 tipo_tarjeta varchar(10) NOT NULL CHECK (tipo_tarjeta IN ('DEBITO','CREDITO')),
 marca varchar(20) NOT NULL DEFAULT 'SENIORLINK',
 saldo numeric(12,2) NOT NULL DEFAULT 0 CHECK (saldo>=0),
 limite_credito numeric(12,2) NOT NULL DEFAULT 0 CHECK (limite_credito>=0),
 credito_utilizado numeric(12,2) NOT NULL DEFAULT 0 CHECK (credito_utilizado BETWEEN 0 AND limite_credito),
 moneda varchar(3) NOT NULL DEFAULT 'PEN' CHECK (moneda='PEN'),
 estado varchar(20) NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA','BLOQUEADA','CANCELADA')),
 creado_en timestamptz NOT NULL DEFAULT now(),
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 version bigint NOT NULL DEFAULT 0,
 CHECK ((tipo_tarjeta='DEBITO' AND limite_credito=0 AND credito_utilizado=0) OR (tipo_tarjeta='CREDITO' AND saldo=0))
);
CREATE INDEX IF NOT EXISTS idx_tarjetas_titular ON pasarela.tarjetas(titular_dni);
COMMIT;
